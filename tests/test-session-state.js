const fs = require('fs');
const vm = require('vm');
const code = fs.readFileSync(__dirname + '/../src/main/webapp/js/session-state.js', 'utf8');
const data = {};
const localStorage = {getItem:k=>Object.prototype.hasOwnProperty.call(data,k)?data[k]:null,setItem:(k,v)=>{data[k]=String(v)},removeItem:k=>{delete data[k]}};
const ctx = {console, Date, localStorage}; ctx.globalThis=ctx; ctx.window=ctx;
vm.runInNewContext(code, ctx);
const S=ctx.SageSessionState;
if(!S) throw new Error('SageSessionState missing');
let settings=S.getSettings();
if(settings.volume!==1 || settings.resumeEnabled!==true || settings.startLiveAtEdge!==true || settings.autoPlayNext!==false || settings.autoSkipCommercials!==false || settings.tenFootMode!==false || settings.syncSageProgress!==false) throw new Error('bad defaults');
settings=S.updateSettings({volume:.4,preferredAudioLang:'SPA',offlineOnly:true,autoPlayNext:true,autoSkipCommercials:true,tenFootMode:true,syncSageProgress:true});
if(settings.volume!==.4 || settings.preferredAudioLang!=='spa' || settings.offlineOnly!==true || settings.autoPlayNext!==true || settings.autoSkipCommercials!==true || settings.tenFootMode!==true || settings.syncSageProgress!==true) throw new Error('settings persistence failed');
S.saveResume(246520,0,125,3600,'NOVA');
let r=S.getResume(246520,0);
if(!r || Math.round(r.position)!==125) throw new Error('resume save failed');
S.saveResume(246520,0,3580,3600,'NOVA');
if(S.getResume(246520,0)!==null) throw new Error('near-end resume should clear');
S.markPlayed({id:246520,segment:0,title:'NOVA',episode:'Test'});
S.markPlayed({id:246520,segment:0,title:'NOVA',episode:'Test'});
if(S.getRecent().length!==1) throw new Error('recent dedupe failed');
if(S.isFavorite(246520)) throw new Error('favorite default bad');
if(!S.toggleFavorite(246520) || !S.isFavorite(246520)) throw new Error('favorite add failed');
if(S.toggleFavorite(246520) || S.isFavorite(246520)) throw new Error('favorite remove failed');
console.log('session state PASS');
